// Generates src/lib/<Name>.ts public entry files.
// Public = every .ts/.tsx file inside a subfolder of src/components, plus the top-level
// files of src/theme. Files with no runtime export (type-only) get no entry.
// Files placed directly in src/components stay demo-only.
import { existsSync, mkdirSync, readdirSync, readFileSync, rmSync, writeFileSync } from 'node:fs';
import path from 'node:path';

const root = path.join(import.meta.dirname, '..');
const src = path.join(root, 'src');
const libDir = path.join(src, 'lib');
const HEADER = '// Generated by scripts/generate-lib-entries.mjs - do not edit.\n';

const isSource = (f) => /\.tsx?$/.test(f) && !/\.stories(-hide)?\.tsx?$/.test(f) && !f.endsWith('.d.ts');
const list = (dir) => readdirSync(dir, { withFileTypes: true });

const sources = [];
for (const d of list(path.join(src, 'components'))) {
  if (d.isDirectory()) {
    for (const f of list(path.join(src, 'components', d.name))) {
      if (f.isFile() && isSource(f.name)) sources.push(path.join(src, 'components', d.name, f.name));
    }
  }
}
for (const f of list(path.join(src, 'theme'))) {
  if (f.isFile() && isSource(f.name)) sources.push(path.join(src, 'theme', f.name));
}

const all = (code, re) => [...code.matchAll(re)].map((m) => m[1]);
const entries = new Map();

for (const file of sources.sort()) {
  const code = readFileSync(file, 'utf8');
  const name = path.basename(file).replace(/\.tsx?$/, '');
  const hasDefault = /^export default /m.test(code);
  const values = all(code, /^export (?:const|function|class|enum) (\w+)/gm);
  const types = [
    ...all(code, /^export (?:interface|type) (\w+)/gm),
    ...[...code.matchAll(/^export type \{([^}]*)\}/gm)].flatMap((m) => m[1].split(',').map((t) => t.trim()).filter(Boolean)),
  ];
  if (!hasDefault && values.length === 0) continue;
  if (entries.has(name)) {
    throw new Error(`Duplicate public component name "${name}": ${entries.get(name).file} and ${file}`);
  }
  const specifier = '../' + path.relative(src, file).replace(/\.tsx?$/, '').split(path.sep).join('/');
  const specifiers = [
    ...(hasDefault ? [`default as ${name}`] : []),
    ...values,
    ...types.map((t) => `type ${t}`),
  ];
  entries.set(name, { file, text: `${HEADER}export { ${specifiers.join(', ')} } from '${specifier}';\n` });
}

mkdirSync(libDir, { recursive: true });
for (const f of readdirSync(libDir)) {
  const full = path.join(libDir, f);
  const name = f.replace(/\.ts$/, '');
  if (f.endsWith('.ts') && !entries.has(name) && readFileSync(full, 'utf8').startsWith(HEADER)) {
    rmSync(full);
    console.log(`removed stale src/lib/${f}`);
  }
}
for (const [name, { text }] of entries) {
  const out = path.join(libDir, `${name}.ts`);
  if (!existsSync(out) || readFileSync(out, 'utf8') !== text) {
    writeFileSync(out, text);
    console.log(`wrote src/lib/${name}.ts`);
  }
}
console.log(`${entries.size} public entries`);
